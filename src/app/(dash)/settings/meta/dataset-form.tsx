"use client";

import { useState, useTransition } from "react";
import { useRouter } from "next/navigation";
import { saveMetaDatasetAction } from "@/app/actions/meta";
import type { Campaign, MetaDataset, Site, Stage } from "@/lib/types";

/**
 * Add or edit one dataset.
 *
 * Deliberately the same form for both. A second ad account is added exactly
 * the way the first one was, which is the whole point of building this around
 * a list rather than a settings screen.
 */
export default function DatasetForm({
  existing,
  campaigns,
  sites,
  stages,
  defaultSource,
  onDone,
}: {
  existing?: MetaDataset;
  campaigns: Campaign[];
  sites: Site[];
  stages: Stage[];
  defaultSource: string;
  onDone?: () => void;
}) {
  const router = useRouter();
  const [err, setErr] = useState("");
  const [busy, start] = useTransition();

  const [name, setName] = useState(existing?.name ?? "");
  const [datasetId, setDatasetId] = useState(existing?.dataset_id ?? "");
  const [token, setToken] = useState("");
  const [testCode, setTestCode] = useState(existing?.test_code ?? "");
  const [source, setSource] = useState(existing?.lead_event_source ?? defaultSource);
  const [formId, setFormId] = useState(existing?.form_id ? String(existing.form_id) : "");
  const [siteId, setSiteId] = useState(existing?.site_id ? String(existing.site_id) : "");
  const [picked, setPicked] = useState<string[]>(existing?.stages ?? []);

  const toggle = (key: string) =>
    setPicked((list) => (list.includes(key) ? list.filter((k) => k !== key) : [...list, key]));

  const submit = () => {
    setErr("");
    start(async () => {
      const res = await saveMetaDatasetAction(existing?.id ?? null, {
        name,
        dataset_id: datasetId,
        access_token: token,
        test_code: testCode,
        lead_event_source: source,
        form_id: formId ? Number(formId) : 0,
        site_id: siteId ? Number(siteId) : 0,
        stages: picked,
      });
      if ("error" in res) {
        setErr(res.error);
        return;
      }
      setToken("");
      router.refresh();
      onDone?.();
    });
  };

  return (
    <div className="card">
      <h2>{existing ? `Edit ${existing.name}` : "Add a dataset"}</h2>

      {err && (
        <div className="msg err" role="alert">
          {err}
        </div>
      )}

      <div className="grid2" style={{ gap: 14 }}>
        <label>
          <strong>Name</strong>
          <input
            type="text"
            value={name}
            disabled={busy}
            onChange={(e) => setName(e.target.value)}
            placeholder="Rice mill campaign — Q4"
          />
          <small style={{ color: "var(--muted)" }}>
            Only for you. Name it after the campaign so you can tell them apart later.
          </small>
        </label>

        <label>
          <strong>Dataset ID</strong>
          <input
            type="text"
            inputMode="numeric"
            value={datasetId}
            disabled={busy}
            onChange={(e) => setDatasetId(e.target.value)}
            placeholder="1519673909485931"
          />
          <small style={{ color: "var(--muted)" }}>
            The number Events Manager shows beside the endpoint, not the whole URL.
          </small>
        </label>

        <label style={{ gridColumn: "1 / -1" }}>
          <strong>Access token</strong>
          <input
            type="password"
            value={token}
            disabled={busy}
            autoComplete="off"
            onChange={(e) => setToken(e.target.value)}
            placeholder={existing?.has_token ? "Saved — leave blank to keep it" : "Paste the dataset access token"}
          />
          <small style={{ color: "var(--muted)" }}>
            Generated by <strong>Generate Access Token</strong> on the same Events Manager screen.
            Stored encrypted and never shown again — leave blank when editing to keep the current one.
          </small>
        </label>

        <label>
          <strong>Test event code</strong>
          <input
            type="text"
            value={testCode}
            disabled={busy}
            onChange={(e) => setTestCode(e.target.value)}
            placeholder="Optional — TEST12345"
          />
          <small style={{ color: "var(--muted)" }}>
            While this is set, everything goes to the <strong>Test Events</strong> tab instead of
            your real data. Clear it to go live.
          </small>
        </label>

        <label>
          <strong>CRM name sent to Meta</strong>
          <input
            type="text"
            value={source}
            disabled={busy}
            onChange={(e) => setSource(e.target.value)}
          />
          <small style={{ color: "var(--muted)" }}>
            Meta&rsquo;s <code>lead_event_source</code>. Any name identifying this CRM.
          </small>
        </label>

        <label>
          <strong>Only this campaign</strong>
          <select value={formId} disabled={busy} onChange={(e) => setFormId(e.target.value)}>
            <option value="">Every campaign</option>
            {campaigns.map((c) => (
              <option key={c.id} value={c.id}>
                {c.name}
              </option>
            ))}
          </select>
        </label>

        <label>
          <strong>Only this website</strong>
          <select value={siteId} disabled={busy} onChange={(e) => setSiteId(e.target.value)}>
            <option value="">Every website</option>
            {sites.map((s) => (
              <option key={s.id} value={s.id}>
                {s.name}
              </option>
            ))}
          </select>
        </label>
      </div>

      <div style={{ marginTop: 18 }}>
        <strong>Stages to report</strong>
        <p style={{ fontSize: 13, color: "var(--muted)", margin: "4px 0 10px" }}>
          Meta asks for every stage of the funnel, including the first, so it can learn the shape
          of the whole thing. Leave all unticked to send them all.
        </p>
        <div className="row" style={{ flexWrap: "wrap", gap: 8 }}>
          {stages.map((s) => (
            <label
              key={s.key}
              className="pill"
              style={{
                cursor: "pointer",
                display: "inline-flex",
                alignItems: "center",
                gap: 6,
                borderLeft: `3px solid ${s.colour}`,
                opacity: picked.length === 0 || picked.includes(s.key) ? 1 : 0.45,
              }}
            >
              <input
                type="checkbox"
                checked={picked.includes(s.key)}
                disabled={busy}
                onChange={() => toggle(s.key)}
              />
              {s.label}
            </label>
          ))}
        </div>
      </div>

      <div className="row" style={{ gap: 10, marginTop: 18 }}>
        <button className="btn" onClick={submit} disabled={busy}>
          {busy ? "Saving…" : existing ? "Save changes" : "Add dataset"}
        </button>
        {onDone && (
          <button className="btn ghost" onClick={onDone} disabled={busy}>
            Cancel
          </button>
        )}
      </div>
    </div>
  );
}
